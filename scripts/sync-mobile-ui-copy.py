"""Keep both Flutter apps on the same exact-copy catalog as the website."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def read(path):
    return json.loads((ROOT / path).read_text(encoding='utf-8'))
copy = read('apps/web/src/lib/ui-copy.json')
copy.update(read('packages/flutter_core/mobile-ui-copy.json'))
aliases = read('apps/web/src/lib/ui-aliases.json')
aliases.update(read('packages/flutter_core/mobile-ui-aliases.json'))
def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
def mapping(name, data):
    return 'const Map<String, String> ' + name + ' = {\n' + ''.join(
        f'  {dart(k)}: {dart(v)},\n' for k,v in sorted(data.items())) + '};\n'
output = '// Generated by scripts/sync-mobile-ui-copy.py; edit the source JSON catalogs.\n'
output += mapping('uiCopy', copy) + mapping('uiEnglish', {sw:en for en,sw in copy.items()}) + mapping('uiAliases',aliases)
target=ROOT/'packages/flutter_core/lib/src/ui_copy.dart'
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text(output,encoding='utf-8')
print(f'Shared mobile catalog: {len(copy)} phrases')
