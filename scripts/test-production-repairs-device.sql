\set ON_ERROR_STOP on
begin;
create function pg_temp.assert_true(value boolean,label text) returns void language plpgsql as $$ begin if value is distinct from true then raise exception 'FAIL: %',label; end if; raise notice 'PASS: %',label; end $$;
insert into auth.sessions(id,user_id) values(md5('repair-session-A')::uuid,md5('repair-customer')::uuid),(md5('repair-session-B')::uuid,md5('repair-unrelated')::uuid);
select set_config('request.jwt.claims',jsonb_build_object('sub',md5('repair-customer')::uuid,'role','authenticated','session_id',md5('repair-session-A')::uuid)::text,true);
set local role authenticated;
select register_push_device_v2('fixture-not-a-real-fcm-token','android','customer','fixture-device','sw',repeat('A',40));
reset role;
select pg_temp.assert_true((select session_id=md5('repair-session-A')::uuid and unregister_capability_hash<>repeat('A',40) from device_tokens where device_token='fixture-not-a-real-fcm-token'),'registration binds session and hashes unregistration capability');
select pg_temp.assert_true(push_registration_has_active_session((select id from device_tokens where device_token='fixture-not-a-real-fcm-token')),'active bound Auth session is eligible');
select set_config('request.jwt.claims','{"role":"anon"}',true);
set local role anon;
select unregister_push_installation('fixture-not-a-real-fcm-token',repeat('wrong',8));
reset role;
select pg_temp.assert_true((select is_enabled from device_tokens where device_token='fixture-not-a-real-fcm-token'),'wrong installation capability cannot disable device');
set local role anon;
select unregister_push_installation('fixture-not-a-real-fcm-token',repeat('A',40));
reset role;
select pg_temp.assert_true(not (select is_enabled from device_tokens where device_token='fixture-not-a-real-fcm-token'),'queued logout can disable with capability after auth is cleared');
select set_config('request.jwt.claims',jsonb_build_object('sub',md5('repair-unrelated')::uuid,'role','authenticated','session_id',md5('repair-session-B')::uuid)::text,true);
set local role authenticated;
select register_push_device_v2('fixture-not-a-real-fcm-token','android','customer','fixture-device','en',repeat('B',40));
reset role;
select set_config('request.jwt.claims','{"role":"anon"}',true);
set local role anon;
select unregister_push_installation('fixture-not-a-real-fcm-token',repeat('A',40));
reset role;
select pg_temp.assert_true((select is_enabled and user_id=md5('repair-unrelated')::uuid from device_tokens where device_token='fixture-not-a-real-fcm-token'),'old account capability cannot disable newly registered account');
delete from auth.sessions where id=md5('repair-session-B')::uuid;
select pg_temp.assert_true(not push_registration_has_active_session((select id from device_tokens where device_token='fixture-not-a-real-fcm-token')),'revoked Auth session cannot receive bound notifications');
rollback;
